#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

final_candidate=false

usage() {
    cat <<'USAGE'
Usage: ./scripts/verify.sh [--final-candidate]

  --final-candidate  Require a clean tracked tree and no untracked files, then
                     emit debug APK Git/package/variant/hash/size provenance.

Device/emulator testing is allowed separately from this verifier.
This verifier has no --device mode and does not run connected tests.
USAGE
}

while (($# > 0)); do
    case "$1" in
        --final-candidate)
            final_candidate=true
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            printf 'ERROR: unknown argument: %s\n' "$1" >&2
            usage >&2
            exit 2
            ;;
    esac
    shift
done

head_sha="$(git rev-parse HEAD)"
tree_sha="$(git rev-parse 'HEAD^{tree}')"
branch="$(git branch --show-current)"

printf '%s\n' '=== Hermes Bot Android verification ==='
printf 'Mode: default%s\n' \
    "$($final_candidate && printf '%s' ' + final-candidate')"
printf 'HEAD: %s\n' "$head_sha"
printf 'Tree: %s\n' "$tree_sha"
printf 'Branch: %s\n' "${branch:-DETACHED}"
printf '%s\n' 'Status:'
git status --short --branch

require_clean_candidate() {
    mapfile -t untracked_files < <(git ls-files --others --exclude-standard)
    if ((${#untracked_files[@]} > 0)); then
        printf '%s\n' 'ERROR: final-candidate mode rejects untracked files:' >&2
        printf '  %s\n' "${untracked_files[@]}" >&2
        exit 1
    fi
    if ! git diff --quiet || ! git diff --cached --quiet; then
        printf '%s\n' 'ERROR: final-candidate mode requires no staged or unstaged tracked changes.' >&2
        exit 1
    fi
}

if $final_candidate; then
    require_clean_candidate
fi

run_step() {
    local label="$1"
    shift
    printf '\n=== %s ===\n' "$label"
    "$@"
}

summarize_junit() {
    python3 - <<'PY'
from pathlib import Path
from xml.etree import ElementTree

report_dir = Path("app/build/test-results/testDebugUnitTest")
files = sorted(report_dir.glob("TEST-*.xml"))
if not files:
    print(f"JUnit summary: unavailable (no XML under {report_dir})")
    raise SystemExit(0)

totals = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0}
for path in files:
    # These XML files are generated locally by Gradle/JUnit, never accepted as
    # external input; keeping the summary dependency-free is intentional.
    root = ElementTree.parse(path).getroot()
    for key in totals:
        totals[key] += int(root.attrib.get(key, "0"))
print(
    "JUnit summary: "
    f"tests={totals['tests']} failures={totals['failures']} "
    f"errors={totals['errors']} skipped={totals['skipped']} suites={len(files)}"
)
print("JUnit report: app/build/reports/tests/testDebugUnitTest/index.html")
PY
}

summarize_lint() {
    python3 - <<'PY'
from collections import Counter
from pathlib import Path
from xml.etree import ElementTree

report = Path("app/build/reports/lint-results-debug.xml")
if not report.is_file():
    print(f"Lint summary: unavailable ({report} not found)")
    raise SystemExit(0)

issues = ElementTree.parse(report).getroot().findall("issue")
# The lint report is generated by this local Gradle invocation, not supplied by
# a user or network source; stdlib parsing keeps the verifier dependency-free.
counts = Counter(issue.attrib.get("severity", "Unknown") for issue in issues)
ordered = ["Fatal", "Error", "Warning", "Information", "Ignore", "Unknown"]
parts = [f"total={len(issues)}"]
parts.extend(f"{severity.lower()}={counts[severity]}" for severity in ordered if counts[severity])
print("Lint summary: " + " ".join(parts))
print("Lint reports: app/build/reports/lint-results-debug.xml and app/build/reports/lint-results-debug.html")
PY
}

emit_apk_provenance() {
    local metadata="app/build/outputs/apk/debug/output-metadata.json"
    if [[ ! -f "$metadata" ]]; then
        printf 'ERROR: debug APK metadata not found: %s\n' "$metadata" >&2
        return 1
    fi

    mapfile -t apk_data < <(python3 - "$metadata" <<'PY'
import json
from pathlib import Path
import sys

metadata_path = Path(sys.argv[1])
data = json.loads(metadata_path.read_text(encoding="utf-8"))
elements = data.get("elements", [])
if len(elements) != 1:
    raise SystemExit(f"expected exactly one debug APK element, found {len(elements)}")
element = elements[0]
output_file = element.get("outputFile")
if not output_file:
    raise SystemExit("debug APK metadata has no outputFile")
apk = metadata_path.parent / output_file
if not apk.is_file():
    raise SystemExit(f"declared debug APK does not exist: {apk}")
print(apk.as_posix())
print(data.get("applicationId", "UNKNOWN"))
print(data.get("variantName", "UNKNOWN"))
print(element.get("versionCode", "UNKNOWN"))
print(element.get("versionName", "UNKNOWN"))
PY
    )

    if ((${#apk_data[@]} != 5)); then
        printf '%s\n' 'ERROR: could not read complete debug APK provenance.' >&2
        return 1
    fi

    local apk_path="${apk_data[0]}"
    local application_id="${apk_data[1]}"
    local variant_name="${apk_data[2]}"
    local version_code="${apk_data[3]}"
    local version_name="${apk_data[4]}"
    local apk_sha256
    local apk_size
    apk_sha256="$(sha256sum "$apk_path" | cut -d ' ' -f 1)"
    apk_size="$(stat -c '%s' "$apk_path")"

    printf '\n%s\n' '=== Final-candidate debug APK provenance ==='
    printf 'Git HEAD: %s\n' "$head_sha"
    printf 'Git tree: %s\n' "$tree_sha"
    printf 'APK: %s\n' "$apk_path"
    printf 'SHA-256: %s\n' "$apk_sha256"
    printf 'Size bytes: %s\n' "$apk_size"
    printf 'Package: %s\n' "$application_id"
    printf 'Variant: %s\n' "$variant_name"
    printf 'Version code: %s\n' "$version_code"
    printf 'Version name: %s\n' "$version_name"
}

run_step 'Policy checks' ./scripts/ci-policy-check.sh
run_step 'JVM tests, Android lint, and debug APKs' \
    ./gradlew testDebugUnitTest lintDebug assembleDebug --stacktrace
summarize_junit
summarize_lint

if $final_candidate; then
    if [[ "$(git rev-parse HEAD)" != "$head_sha" || "$(git rev-parse 'HEAD^{tree}')" != "$tree_sha" ]]; then
        printf '%s\n' 'ERROR: Git HEAD/tree changed during final-candidate verification.' >&2
        exit 1
    fi
    require_clean_candidate
    emit_apk_provenance
fi

printf '\n%s\n' '=== Verification PASSED ==='
printf '%s\n' 'Device/emulator testing: allowed separately; not run by this verifier.'
